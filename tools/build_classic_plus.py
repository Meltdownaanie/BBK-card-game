#!/usr/bin/env python3
"""Builds classic-plus.js / classic-plus.css (Standard-mode UI for the Classic page) from
tools/classic-plus.src.js plus the shared pieces of tools/standard-patch.js and tools/standard.css,
so Classic and Standard use the very same jackpot animation, tags and log styles.
Run from the repo root: python3 tools/build_classic_plus.py"""
import os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda *p: open(os.path.join(root, *p), encoding='utf-8').read()
patch, css, src = rd('tools', 'standard-patch.js'), rd('tools', 'standard.css'), rd('tools', 'classic-plus.src.js')

def fn(name):
    """a top-level function of standard-patch.js, up to the next top-level statement"""
    m = re.search(r'^(?:async )?function ' + name + r'\(', patch, re.M)
    assert m, name
    end = re.compile(r'^(?:(?:async )?function |/\*|const |let |//@@)', re.M).search(patch, m.end())
    return patch[m.start():end.start() if end else len(patch)].rstrip() + '\n'

shared = ''.join(fn(n) for n in ['stdTag', 'stdCoinRain', 'stdAura', 'stdJackpot'])
js = src.rstrip() + '\n/* ---- shared with Standard (copied from tools/standard-patch.js by build_classic_plus.py) ---- */\n' + shared + '})();\n'

keep = re.compile(r'jp-|std-lossdisc|std-keep|stdLossShake|std-flytag|\.mu-tag|\.hand-item\{transform:rotate|std-modal|std-log|stdLog|\.lg-|\.fx-ico|\.fxt|\.std-line|\.overlay\.std-builder')
rules = [l for l in css.split('\n') if l.strip() and not l.lstrip().startswith('/*') and keep.search(l)]
out = '/* Classic + : Standard-mode UI pieces for the Classic page (generated by tools/build_classic_plus.py from tools/standard.css) */\n' + '\n'.join(rules) + '\n'
out += '''/* classic-only log rows */
.lg-row.cl-slot{align-items:center}
.lg-row.cl-slot.tie{border-left-color:#8f84b5}
.cl-vs{flex:0 0 auto;font-size:10px;color:#a79bc4}
.lg-card.none{color:#a79bc4;background:#ffffff14;border-top-color:#ffffff22}
.lg-row.cl-combo{border-left-color:#ffcf33}
.lg-row.cl-combo.ai .lg-who{color:#ff9a7a}.lg-row.cl-combo.me .lg-who{color:#4fd1c5}
.cl-disc{margin:2px 0 6px;font-size:11px;color:#b9a9e6}
'''
assert out.count('{') == out.count('}'), 'classic-plus.css: unbalanced braces'
# the JS goes INSIDE the Classic page's main script (its functions are private to that script), between markers
B, E = '//@@CLASSIC_PLUS_BEGIN', '//@@CLASSIC_PLUS_END'
page = rd('index.html')
block = B + ' (generated by tools/build_classic_plus.py from tools/classic-plus.src.js: edit that file, not this block)\n' + js + E + '\n'
if B in page:
    a, z = page.index(B), page.index(E) + len(E) + 1
    page = page[:a] + block + page[z:]
else:
    k = page.rindex('})();\n</script>', 0, page.index("document.getElementById('menuBoard')"))
    page = page[:k] + block + page[k:]
open(os.path.join(root, 'index.html'), 'w', encoding='utf-8').write(page)
open(os.path.join(root, 'classic-plus.css'), 'w', encoding='utf-8').write(out)
print('classic-plus block', len(js), 'classic-plus.css', len(out), 'rules', len(rules))
